{
    static readonly (string Name, double Default)[] Fields =
    [
        ("Weight", 551.5768), ("Standing Height", 1.531), ("Shoulder Height", 1.252), ("Armpit Height", 1.166),
        ("Waist Height", 0.878), ("Seated Height", 0.856), ("Head Length", 0.195), ("Head Breadth", 0.146),
        ("Head to Chin Height", 0.212), ("Neck Circumference", 0.315), ("Shoulder Breadth", 0.338), ("Chest Depth", 0.223),
        ("Chest Breadth", 0.284), ("Waist Depth", 0.206), ("Waist Breadth", 0.295), ("Buttock Depth", 0.208),
        ("Hip Breadth, Standing", 0.338), ("Shoulder to Elbow Length", 0.276), ("Forearm-Hand Length", 0.393), ("Biceps Circumference", 0.276),
        ("Elbow Circumference", 0.234), ("Forearm Circumference", 0.246), ("Waist Circumference", 0.153), ("Knee Height, Seated", 0.457),
        ("Thigh Circumference", 0.598), ("Upper Leg Circumference", 0.521), ("Knee Circumference", 0.366), ("Calf Circumference", 0.369),
        ("Ankle Circumference", 0.223), ("Ankle Height, Outside", 0.063), ("Foot Breadth", 0.088), ("Foot Length", 0.229),
    ];
    readonly ComboBox unit = new() { DropDownStyle = ComboBoxStyle.DropDownList, Items = { "English", "Metric" } };
    readonly TextBox[] boxes = new TextBox[32];
    public double[] Dims { get; } = new double[32];
    public bool Metric => unit.SelectedIndex == 1;

    public BodyDimForm(double[]? current, bool metric)
    {
        Text = "32 Body Dimensions"; AutoSize = true; AutoSizeMode = AutoSizeMode.GrowAndShrink; FormBorderStyle = FormBorderStyle.FixedDialog;
        MaximizeBox = MinimizeBox = false; StartPosition = FormStartPosition.CenterParent;
        var t = new TableLayoutPanel { Dock = DockStyle.Fill, ColumnCount = 4, AutoSize = true, Padding = new Padding(10) };
        t.Controls.Add(new Label { Text = "Units for Input", AutoSize = true, Anchor = AnchorStyles.Left }); t.Controls.Add(unit); t.SetColumnSpan(unit, 3);
        unit.SelectedIndex = metric ? 1 : 0;
        for (int i = 0; i < 32; i++)
        {
            t.Controls.Add(new Label { Text = Fields[i].Name, AutoSize = true, Anchor = AnchorStyles.Left });
            t.Controls.Add(boxes[i] = new TextBox { Width = 90, Text = (current?[i] ?? Fields[i].Default).ToString(CultureInfo.InvariantCulture) });
        }
        var ok = new Button { Text = "OK", AutoSize = true };
        var cancel = new Button { Text = "Cancel", AutoSize = true, DialogResult = DialogResult.Cancel };
        t.Controls.Add(ok); t.Controls.Add(cancel);
        Controls.Add(t); CancelButton = cancel;
        ok.Click += (_, _) =>
        {
            for (int i = 0; i < 32; i++)
                if (!double.TryParse(boxes[i].Text, NumberStyles.Float, CultureInfo.InvariantCulture, out Dims[i]))
                { MessageBox.Show(this, "Invalid input in textbox."); return; }
            DialogResult = DialogResult.OK;
        };
    }
}
